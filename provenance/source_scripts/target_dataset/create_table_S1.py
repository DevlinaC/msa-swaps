"""Build Table S1: one row per target, ordered by length class and length.

Defaults are resolved relative to this script, not the current working directory.
Inputs are targets_{60,100,150}.fa, cath_annotations.csv (generated by
get_CATH_annotations.py), and pdb_info_from_list.csv (protein_name_frm_pdb.py).
No network requests are made; TM-scores and fold recovery are outside this script.

FASTA headers may be >1ABC, >1ABC_A, or >1ABC:A, followed by a description.
The --chain-map CSV (default: target_chains.csv) supplies target chains and
optional short protein_name values from PDB COMPND records. Run get_target_chains.py
first; chain A resolves ties as confirmed for this analysis.
Chain IDs are case-sensitive. Bare PDB IDs do not establish a target chain:
if CATH lists exactly one chain, its annotations are reported as unverified;
if several chains are listed, annotations are withheld as ambiguous. Confirm
chains using the original structures before interpreting chain-level annotations.

Multiple domains are joined with ' | ' in matching order across annotation
columns. Missing CATH rows mean only 'not present in input'; the upstream fetcher
cannot distinguish failed requests from genuinely absent mappings. PDB entry
structure titles are retained verbatim in structure_title; protein_name is the
short display label. Missing CATH annotation cells use literal NA. --xlsx PATH
adds a formatted workbook with a compact table and a detailed reference sheet.

Examples:
    python create_table_S1.py
    python create_table_S1.py --chain-map target_chains.csv
    python create_table_S1.py --fasta-60 elsewhere/60.fa --output table.csv
"""

import argparse
import csv
import os
from pathlib import Path
import re
import sys
import tempfile
import textwrap
import json
import subprocess

BASE_DIR = Path(__file__).resolve().parent
EXPECTED_COUNTS = {60: 14, 100: 10, 150: 10}
FIELDS = [
    "pdb_id", "chain_id", "protein_name", "structure_title", "length_class", "sequence", "length",
    "cath_status", "cath_chain_id", "domain_id", "cath_code", "topology",
    "superfamily", "residue_ranges",
]
ANNOTATION_FIELDS = ["domain_id", "cath_code", "topology", "superfamily", "residue_ranges"]


def read_csv(path, required):
    """Read strings without converting N/A to NaN; reject malformed schemas."""
    with path.open(newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        missing = set(required) - set(reader.fieldnames or [])
        if missing:
            raise ValueError(f"{path}: missing columns {', '.join(sorted(missing))}")
        rows = []
        for number, row in enumerate(reader, 2):
            if None in row or any(value is None for value in row.values()):
                raise ValueError(f"{path}:{number}: malformed CSV row")
            row = {key: value.strip() for key, value in row.items()}
            row["pdb_id"] = row["pdb_id"].upper()
            if not re.fullmatch(r"[0-9][A-Z0-9]{3}", row["pdb_id"]):
                raise ValueError(f"{path}:{number}: invalid PDB ID")
            rows.append(row)
        return rows


def unique_lookup(rows, label):
    """Reject duplicate PDB keys instead of silently selecting a first row."""
    lookup = {}
    for row in rows:
        key = row["pdb_id"]
        if key in lookup:
            raise ValueError(f"{label}: duplicate PDB ID {key}")
        lookup[key] = row
    return lookup


def read_fasta(path):
    """Yield validated (PDB ID, optional chain, sequence) records, including wraps."""
    def record(header, chunks):
        token = header.split()[0] if header.split() else ""
        match = re.fullmatch(r"([0-9][A-Za-z0-9]{3})(?:[_:]([A-Za-z0-9]+))?", token)
        if not match:
            raise ValueError(f"{path}: unsupported FASTA identifier {token!r}")
        sequence = "".join(chunks).upper()
        if not sequence or not re.fullmatch(r"[ACDEFGHIKLMNPQRSTVWYBXZJUO]+", sequence):
            raise ValueError(f"{path}: empty or invalid protein sequence for {token}")
        return match[1].upper(), match[2] or "", sequence

    header, chunks = None, []
    with path.open(encoding="utf-8-sig") as handle:
        for number, line in enumerate(handle, 1):
            line = line.strip()
            if not line:
                continue
            if line.startswith(">"):
                if header is not None:
                    yield record(header, chunks)
                header, chunks = line[1:], []
            else:
                if header is None:
                    raise ValueError(f"{path}:{number}: sequence before FASTA header")
                chunks.append("".join(line.split()))
    if header is not None:
        yield record(header, chunks)


def select_cath(rows, chain):
    """Return selected annotations and an explicit chain/coverage status."""
    if not rows:
        return [], "not_in_input"
    if chain:
        selected = [row for row in rows if row["chain_id"] == chain]
        return selected, "target_chain" if selected else "target_chain_not_in_input"
    chains = {row["chain_id"] for row in rows}
    if len(chains) != 1 or "" in chains or "N/A" in chains:
        return [], "ambiguous_chain"
    return rows, "single_annotated_chain_unverified"


def normalize_missing(value):
    """Use literal NA consistently, without masking a genuine annotation."""
    return "NA" if value.strip().upper() in {"", "N/A", "NA", "NAN", "NONE", "NULL"} else value


def short_title(title):
    """Fallback display label; preserve the original title in structure_title."""
    title = re.sub(r"^(?:solution|crystal|nmr) structure of\s+", "", title, flags=re.I)
    return textwrap.shorten(title, width=80, placeholder="...")


def build_table(fasta_paths, names, cath_rows, chain_map):
    """Validate the README's 34 targets and assemble one row per protein."""
    cath_by_pdb = {}
    for row in cath_rows:
        cath_by_pdb.setdefault(row["pdb_id"], []).append(row)
    table, seen = [], set()
    for size, path in fasta_paths.items():
        records = list(read_fasta(path))
        if len(records) != EXPECTED_COUNTS[size]:
            raise ValueError(f"{path}: expected {EXPECTED_COUNTS[size]} targets, found {len(records)}")
        for pdb_id, header_chain, sequence in records:
            if pdb_id in seen:
                raise ValueError(f"Duplicate target {pdb_id} across FASTA records")
            seen.add(pdb_id)
            if pdb_id not in names or names[pdb_id]["protein_name"].upper() in {"", "N/A", "NA", "NAN"}:
                raise ValueError(f"Missing structure title for {pdb_id}")
            mapped_chain = chain_map.get(pdb_id, {}).get("chain_id", "")
            if mapped_chain and header_chain and mapped_chain != header_chain:
                raise ValueError(f"Conflicting target chains for {pdb_id}")
            chain = mapped_chain or header_chain
            selected, status = select_cath(cath_by_pdb.get(pdb_id, []), chain)
            # Deduplicate identical annotations while preserving domain associations.
            domains = sorted({tuple(row[field] for field in ANNOTATION_FIELDS) for row in selected})
            result = {
                "pdb_id": pdb_id, "chain_id": chain,
                "protein_name": chain_map.get(pdb_id, {}).get("protein_name") or short_title(names[pdb_id]["protein_name"]),
                "structure_title": names[pdb_id]["protein_name"],
                "length_class": size, "sequence": sequence, "length": len(sequence),
                "cath_status": status,
                "cath_chain_id": selected[0]["chain_id"] if selected else "NA",
            }
            for index, field in enumerate(ANNOTATION_FIELDS):
                result[field] = " | ".join(normalize_missing(domain[index]) for domain in domains) if domains else "NA"
            table.append(result)
    unused = set(chain_map) - seen
    if unused:
        raise ValueError(f"Chain map contains unknown targets: {', '.join(sorted(unused))}")
    return sorted(table, key=lambda row: (row["length_class"], row["length"], row["pdb_id"]))


def write_table(path, rows):
    """Publish atomically so validation/write failures do not leave a partial CSV."""
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", newline="", encoding="utf-8", dir=path.parent,
                                         prefix=f".{path.name}.", suffix=".tmp", delete=False) as handle:
            temporary = Path(handle.name)
            writer = csv.DictWriter(handle, fieldnames=FIELDS)
            writer.writeheader()
            writer.writerows(rows)
        os.replace(temporary, path)
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()


def main(argv=None):
    """CLI entry point; importing this module performs no I/O."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    for size in EXPECTED_COUNTS:
        parser.add_argument(f"--fasta-{size}", type=Path, default=BASE_DIR / f"targets_{size}.fa")
    parser.add_argument("--names", type=Path, default=BASE_DIR / "pdb_info_from_list.csv")
    parser.add_argument("--cath", type=Path, default=BASE_DIR / "cath_annotations.csv")
    parser.add_argument("--chain-map", type=Path, default=BASE_DIR / "target_chains.csv", help="Optional CSV: pdb_id,chain_id (case-sensitive chains)")
    parser.add_argument("--output", type=Path, default=BASE_DIR / "table_S1.csv")
    parser.add_argument("--xlsx", type=Path, help="Also create a formatted Excel workbook (Node.js/artifact-tool required)")
    args = parser.parse_args(argv)
    try:
        paths = {size: getattr(args, f"fasta_{size}") for size in EXPECTED_COUNTS}
        inputs = [*paths.values(), args.names, args.cath] + ([args.chain_map] if args.chain_map else [])
        if args.xlsx and (args.xlsx.resolve() in {p.resolve() for p in inputs} or args.xlsx.resolve() == args.output.resolve()):
            raise ValueError("Excel output must not overwrite CSV output or inputs")
        if args.output.resolve() in {path.resolve() for path in inputs}:
            raise ValueError("Output must not overwrite an input file")
        names = unique_lookup(read_csv(args.names, ["pdb_id", "protein_name"]), args.names)
        cath_rows = read_csv(args.cath, ["pdb_id", "chain_id", *ANNOTATION_FIELDS])
        chain_map = unique_lookup(read_csv(args.chain_map, ["pdb_id", "chain_id"]), args.chain_map) if args.chain_map else {}
        if any(not re.fullmatch(r"[A-Za-z0-9]+", row["chain_id"]) or row["chain_id"] == "N/A" for row in chain_map.values()):
            raise ValueError("Chain map must contain nonempty, alphanumeric chain IDs")
        table = build_table(paths, names, cath_rows, chain_map)
        if args.xlsx:
            subprocess.run(["node", str(BASE_DIR / "export_table_S1.mjs"), str(args.xlsx.resolve())],
                           input=json.dumps(table), text=True, check=True)
        write_table(args.output, table)
    except (OSError, ValueError, csv.Error, subprocess.CalledProcessError) as error:
        parser.exit(1, f"Error: {error}\n")
    print(f"Wrote {len(table)} targets (14/10/10 by length class) to {args.output}")
    for status in sorted({row["cath_status"] for row in table}):
        ids = [row["pdb_id"] for row in table if row["cath_status"] == status]
        print(f"CATH {status}: {len(ids)} ({', '.join(ids)})", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
